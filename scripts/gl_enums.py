"""Writes src/gl/enums.gen.rs: GL ES 3.0's enum values (every GL_* define of GLES3/gl3.h with a number) as
constants on `Gl`, and their names.

    python3 scripts/gl_enums.py [/usr/include/GLES3/gl3.h]
"""
import re
import sys
from pathlib import Path


class Header:
    DEFINE = re.compile(r"#define GL_(\w+)\s+(0x[0-9A-Fa-f]+|\d+)u?\s*$")
    SKIP = ("ES_VERSION_", "GLEXT_")

    def __init__(self, path):
        self.path = path

    def enums(self):
        seen = set()
        for line in Path(self.path).read_text().splitlines():
            m = Header.DEFINE.match(line)
            if not m or m.group(1).startswith(Header.SKIP) or m.group(1) in seen:
                continue
            seen.add(m.group(1))
            yield m.group(1), int(m.group(2), 0)

    def rust(self):
        enums = list(self.enums())
        out = [
            f"// Generated by scripts/gl_enums.py from {Path(self.path).name}: do not edit.",
            "",
            "/// GL ES 3.0's enum values (GLES3/gl3.h), without the GL_ prefix",
            "pub struct Gl;",
            "",
            "#[allow(non_upper_case_globals, reason = \"GL's own names, FLOAT_MAT2x3 and the like\")]",
        "impl Gl {",
        ]
        out += [f"    pub const {n}: u32 = {v:#06x};" for n, v in enums]
        out += ["", "    /// Every value by its name", "    pub const NAMES: &[(&str, u32)] = &["]
        out += [f'        ("{n}", Gl::{n}),' for n, _ in enums]
        out += ["    ];", "}", ""]
        return "\n".join(out)


if __name__ == "__main__":
    header = Header(sys.argv[1] if len(sys.argv) > 1 else "/usr/include/GLES3/gl3.h")
    Path(__file__).resolve().parent.parent.joinpath("src/gl/enums.gen.rs").write_text(header.rust())
