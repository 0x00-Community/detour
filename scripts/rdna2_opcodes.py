#!/usr/bin/env python3
"""scripts/data/amd/gfx10-opcodes.json (Mesa ACO's GFX10 instructions, dumped by rdna2_opcodes_dump.py) ⇒
src/dialect/rdna2/opcodes.gen.rs: `Format` (the encodings) and `Opcode` (every instruction, its format and GFX10
opcode).
`--check`: fail when the file is stale."""
import json, os, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
insts = json.load(open(os.path.join(root, 'scripts/data/amd/gfx10-opcodes.json')))
ORDER = ['SOP1', 'SOP2', 'SOPK', 'SOPP', 'SOPC', 'SMEM', 'DS', 'FLAT', 'GLOBAL', 'SCRATCH', 'VOP1', 'VOP2', 'VOPC', 'VOP3',
         'VOP3P', 'MUBUF', 'MTBUF', 'MIMG', 'EXP', 'VINTRP']
FORMATS = set(ORDER)


def camel(name):
    return ''.join(w[:1].upper() + w[1:].lower() for w in name.split('_'))


def fmt(f):
    assert f in FORMATS, f
    return f[:1] + f[1:].lower()


out = ['// Generated by scripts/rdna2_opcodes.py from scripts/data/amd/gfx10-opcodes.json (Mesa ACO); do not edit.\n\n'
       '/// An instruction encoding.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum Format {\n'
       + ''.join(f'    {fmt(f)},\n' for f in ORDER) + '}\n\n']
out.append('/// Every instruction GFX10 encodes (Mesa ACO\'s table), named as ACO names it; [`Opcode::format`] and\n'
           '/// [`Opcode::code`] are what it encodes as.\n'
           '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\npub enum Opcode {\n')
out += [f'    {camel(i["name"])},\n' for i in insts]
out.append('}\n\nimpl Opcode {\n    /// Its encoding family.\n    pub const fn format(self) -> Format {\n        match self {\n')
out += [f'            Self::{camel(i["name"])} => Format::{fmt(i["format"])},\n' for i in insts]
out.append('        }\n    }\n\n    /// Its GFX10 opcode within the format.\n    pub const fn code(self) -> u32 {\n        match self {\n')
out += [f'            Self::{camel(i["name"])} => {i["opcode"]:#x},\n' for i in insts]
out.append('        }\n    }\n}\n')
text = ''.join(out)
path = os.path.join(root, 'src/dialect/rdna2/opcodes.gen.rs')
if '--check' in sys.argv:
    sys.exit(0 if open(path).read() == text else 'stale: ' + path)
open(path, 'w').write(text)
print(len(insts), 'instructions')
